@mcp.tool()
async def get_backtest_trades(
    session_id: str,
    symbol: Optional[str] = None,
    page: int = 1,
    limit: int = 50,
    sort_by: str = "entry_date",
    sort_dir: str = "desc",
    trade_type: Optional[str] = None,
    exit_reason: Optional[str] = None,
    pattern: Optional[str] = None,
    outcome: Optional[str] = None,
    search: Optional[str] = None,
) -> str:
    """Get paginated trades for a backtest session with optional filters.

    Args:
        session_id: The backtest session ID.
        symbol: Filter trades by stock symbol.
        page: Page number for pagination (default 1).
        limit: Number of trades per page (default 50).
        sort_by: Field to sort by (default "entry_date").
        sort_dir: Sort direction — "asc" or "desc" (default "desc").
        trade_type: Filter by trade type.
        exit_reason: Filter by exit reason.
        pattern: Filter by chart pattern.
        outcome: Filter by trade outcome (e.g. "WIN", "LOSS").
        search: Free-text search across trade fields.
    """
    params: dict = {
        "page": page,
        "limit": limit,
        "sort_by": sort_by,
        "sort_dir": sort_dir,
    }
    if symbol:
        params["symbol"] = symbol
    if trade_type:
        params["trade_type"] = trade_type
    if exit_reason:
        params["exit_reason"] = exit_reason
    if pattern:
        params["pattern"] = pattern
    if outcome:
        params["outcome"] = outcome
    if search:
        params["search"] = search
    return await _request("GET", f"/backtests/{session_id}/trades", params=params)


