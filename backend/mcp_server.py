@mcp.tool()
async def health_check() -> str:
    """Check if the trading backend is running and healthy."""
    return await _request("GET", "/")


@mcp.tool()
async def analyze_stock(symbol: str) -> str:
    """Run technical analysis on a single stock.

    Args:
        symbol: The stock ticker symbol to analyze (e.g. "RELIANCE", "TCS").
    """
    return await _request("GET", f"/analyze_stock/{symbol}")


@mcp.tool()
async def get_recommendations() -> str:
    """Retrieve all current stock recommendations generated by the system."""
    return await _request("GET", "/recommendations")


@mcp.tool()
async def update_recommendation(symbol: str, updates: Union[dict, str]) -> str:
    """Update a specific stock recommendation.

    Args:
        symbol: The stock ticker symbol whose recommendation to update.
        updates: A dictionary or JSON string with the fields to update (e.g. '{"action": "BUY"}').
    """
    try:
        body = _parse_updates(updates)
    except ValueError as exc:
        return json.dumps({"error": str(exc)})
    return await _request("PATCH", f"/recommendations/{symbol}", json_body=body)


