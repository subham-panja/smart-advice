# ---------------------------------------------------------------------------


def _parse_updates(updates: Union[dict, str]) -> dict:
    """Safely parse dict or JSON string updates payload."""
    if isinstance(updates, dict):
        return updates
    try:
        return json.loads(updates)
    except Exception as exc:
        raise ValueError(f"Invalid JSON provided for updates: {exc}") from exc


async def _request(
    method: str,
    path: str,
    *,
    params: dict | None = None,
    json_body: dict | None = None,
) -> str:
    """Make an HTTP request to the backend and return the response as a string.

    Supports both direct endpoints (e.g. /positions) and /api prefixed routes.
    """
    clean_path = "/" + path.lstrip("/")
    url = f"{BACKEND_URL}{clean_path}"
    try:
        async with httpx.AsyncClient(timeout=REQUEST_TIMEOUT) as client:
            response = await client.request(
                method,
                url,
                params=params,
                json=json_body,
            )
            # If 404 and path does not start with /api, try with /api prefix as fallback
            if response.status_code == 404 and not clean_path.startswith("/api/"):
                api_url = f"{BACKEND_URL}/api{clean_path}"
                try:
                    fallback_resp = await client.request(
                        method,
                        api_url,
                        params=params,
                        json=json_body,
                    )
                    if fallback_resp.status_code != 404:
                        response = fallback_resp
                except Exception:
                    pass

            # Try to return pretty-printed JSON; fall back to raw text.
            try:
                data = response.json()
                return json.dumps(data, indent=2, default=str)
            except Exception:
                return response.text
    except httpx.ConnectError:
        return json.dumps(
            {
                "error": "Connection refused",
                "detail": (
                    f"Could not connect to the backend at {BACKEND_URL}. "
                    "Make sure the Smart Advice Trading server is running."
                ),
            }
        )
    except httpx.TimeoutException:
        return json.dumps(
            {
                "error": "Request timed out",
                "detail": (f"The request to {BACKEND_URL}{clean_path} timed out after " f"{REQUEST_TIMEOUT}s."),
            }
        )
    except Exception as exc:
        return json.dumps({"error": str(exc)})


