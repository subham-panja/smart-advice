@mcp.tool()
async def run_intraday_backtest(
    strategy: str = "Intraday_Trading_v1",
    period: str = "730d",
    symbols: Optional[str] = None,
) -> str:
    """Run an intraday backtest with a given strategy and symbol list.

    Args:
        strategy: Name of the trading strategy to backtest (default "Intraday_Trading_v1").
        period: Time period for the backtest (default "730d"). Options: "30d", "60d", "180d", "365d", "730d".
        symbols: Comma-separated list of stock symbols (e.g. "RELIANCE,TCS,INFY"). If omitted, uses default watchlist.
    """
    body: dict = {
        "strategy": strategy,
        "period": period,
    }
    if symbols:
        body["symbols"] = [s.strip() for s in symbols.split(",") if s.strip()]
    return await _request(
        "POST",
        "/backtests/run-intraday",
        json_body=body,
    )


